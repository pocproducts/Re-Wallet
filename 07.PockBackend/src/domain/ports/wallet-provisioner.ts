/**
 * PORT: create one wallet for one person.
 *
 * ── Why the chain type is ours and not Privy's ─────────────────────────────────
 *
 * Privy calls it `WalletChainType` and uses it across twenty places in its own
 * surface. If the domain imported that type, the ordering rule — which is a fact
 * about ReWALLET — would be bound to a provider's vocabulary, which can change.
 *
 * The adapter translates `WalletChain` → Privy's type, in **one** place, and that
 * place is what gets edited if the provider renames something.
 *
 * ── Why idempotency is part of the port ───────────────────────────────────────
 *
 * Provisioning the same person twice is an **orphaned wallet**, and there is no
 * clean way to recover one. So the key travels in the interface: if it lived in
 * the implementation, refactoring it away would go unnoticed until somebody saw
 * extra wallets in the database.
 */
import type { WalletChain } from '../wallet/chains';

export interface ProvisionWalletInput {
  /** The person, in Privy's vocabulary: their DID. */
  readonly ownerDid: string;

  readonly chain: WalletChain;

  /**
   * Idempotency key. **Generated by the use case, not by the adapter.**
   *
   * Shape `<ownerDid>:<chain>`: provisioning the same person on the same chain
   * returns the wallet that already exists instead of creating a second one.
   */
  readonly idempotencyKey: string;
}

export interface ProvisionedWallet {
  /** The wallet id in the provider's vocabulary. */
  readonly providerWalletId: string;
  readonly address: string;
  readonly chain: WalletChain;
}

export interface WalletProvisioner {
  provision(input: ProvisionWalletInput): Promise<ProvisionedWallet>;
}